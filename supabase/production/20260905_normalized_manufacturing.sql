-- No schema exposure/config change. Server-side reads use this bounded RPC.
create function public.manufacturing_read_entity(p_entity text, p_offset integer default 0, p_limit integer default 500)
returns jsonb language plpgsql stable security definer set search_path = '' as $read$
declare result jsonb;
begin
  if p_entity not in ('assemblies','parts','requirements','operations','finishing','locations')
     or p_offset < 0 or p_limit < 1 or p_limit > 500 then raise exception 'Invalid manufacturing page'; end if;
  execute format('select jsonb_build_object(''rows'', coalesce((select jsonb_agg(to_jsonb(r)) from
    (select * from manufacturing.%I order by id offset $1 limit $2) r), ''[]''::jsonb),
    ''total'', (select count(*) from manufacturing.%I))', p_entity, p_entity)
    into result using p_offset, p_limit;
  return result;
end;
$read$;
revoke all on function public.manufacturing_read_entity(text,integer,integer) from public, anon, authenticated;
grant execute on function public.manufacturing_read_entity(text,integer,integer) to service_role;
commit;
